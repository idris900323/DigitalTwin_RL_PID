"""Kd-bound check (supplement, POST HOC): macros and table from results/kd_bound_check_v3_90k/ (after ``kd_bound_check.py --summarize``). Simulation only."""

from __future__ import annotations

import csv
import json
import sys

import numpy as np
from analysis import GEN, REGIMES, RESULTS, bootstrap_ci, wilcoxon_p

FOLDER = "kd_bound_check_v3_90k"
PAIRS = [("best_constant_ext", "best_constant"), ("best_constant_ext_kd4", "best_constant"), ("best_constant_ext_kd4", "best_constant_ext"),
         ("ppo", "best_constant"), ("ppo", "best_constant_ext"), ("ppo", "best_constant_ext_kd4")]
LABEL = {"best_constant": "original constant", "best_constant_ext": "extended constant (Kd $\\le2$)", "best_constant_ext_kd4": "extended constant (Kd $\\le4$)", "ppo": "policy"}


def mn(x: float) -> str:
    return f"{x:+.2f}".replace("-", "$-$")


def main() -> int:
    d = RESULTS / FOLDER
    if not (d / "per_episode.csv").exists():
        print("no Kd-bound results yet")
        return 0
    rows = list(csv.DictReader(open(d / "per_episode.csv", encoding="utf-8")))
    consts = json.loads((d / "constants.json").read_text(encoding="utf-8"))
    by: dict = {}
    for r in rows:
        by.setdefault(r["regime"], {}).setdefault(r["controller"], []).append(r)
    macros = {}
    tex = [r"\begin{table*}[t]", r"\centering", r"\small",
           r"\caption{\textbf{Post hoc, supplement.} Kd-bound check: the extended-constant search repeated with the $K_d$ upper bound raised from $2$ to $4$ (constants only; the policy keeps its training "
           r"environment), constants derived on validation seeds, evaluated once on fresh seeds 90000--90099, feasible scenarios. Paired return difference A$-$B: median [95\,\% CI], mean, IQR; unadjusted Wilcoxon $p$.}",
           r"\label{tab:kdbound}", r"\begin{tabular}{llrrrr}", r"\toprule", r"Regime (constants) & A $-$ B & $\Delta$ median [95\,\% CI] & $\Delta$ mean & IQR of $\Delta$ & $p$\\", r"\midrule"]
    for reg in REGIMES:
        if reg not in by:
            continue
        R = {"static": "Static", "changes": "Changes", "ood": "Ood"}[reg]
        c = consts[reg]
        feas = np.array([float(r["margin"]) >= 1.0 for r in by[reg]["best_constant"]])

        def ret(n, reg=reg, feas=feas):
            return np.array([float(r["ret"]) for r in by[reg][n]])[feas]
        macros[f"KdBound{R}Kptwo"] = f"{c['best_constant_ext'][0]:.1f}"
        macros[f"KdBound{R}Kdtwo"] = f"{c['best_constant_ext'][2]:.2f}"
        macros[f"KdBound{R}Kpfour"] = f"{c['best_constant_ext_kd4'][0]:.1f}"
        macros[f"KdBound{R}Kdfour"] = f"{c['best_constant_ext_kd4'][2]:.2f}"
        macros[f"KdBound{R}ValTwo"] = mn(c["val_return_ext"])
        macros[f"KdBound{R}ValFour"] = mn(c["val_return_ext_kd4"])
        first = True
        for A, B in PAIRS:
            dd = ret(A) - ret(B)
            lo, hi = bootstrap_ci(dd, np.median)
            q1, q3 = np.percentile(dd, [25, 75])
            tag = "".join(w.capitalize() for w in f"{A} {B}".replace("kd4", "kdfour").replace("_", " ").split())
            for nm, v in (("Med", np.median(dd)), ("Lo", lo), ("Hi", hi), ("Mean", dd.mean()), ("Qone", q1), ("Qthree", q3)):
                macros[f"KdBound{R}{tag}{nm}"] = mn(v)
            lab = f"{reg} (Kp {c['best_constant_ext_kd4'][0]:.1f}, Kd {c['best_constant_ext_kd4'][2]:.2f})" if first else ""
            tex.append(f"{lab} & {LABEL[A]} $-$ {LABEL[B]} & {mn(np.median(dd))} [{mn(lo)}, {mn(hi)}] & {mn(dd.mean())} & [{mn(q1)}, {mn(q3)}] & {wilcoxon_p(dd):.2g}\\\\")
            first = False
        tex.append(r"\midrule")
    tex[-1] = r"\bottomrule"
    tex += [r"\end{tabular}", r"\end{table*}"]
    (GEN / "tab_kd_bound.tex").write_text("\n".join(tex) + "\n", encoding="utf-8", newline="\n")
    (GEN / "numbers_kd.tex").write_text("% generated by paper/kd_bound.py\n" + "\n".join(f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(macros.items())) + "\n", encoding="utf-8", newline="\n")
    print("Kd-bound macros and table written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
